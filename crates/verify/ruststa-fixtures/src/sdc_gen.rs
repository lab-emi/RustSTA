//! Deterministic SDC constraint generators paired with the synthetic netlist topologies.

use std::fmt::Write;

use crate::r#gen::{NetlistFixture, synthetic_netlists};

/// Generates a single-clock SDC constraint deck with input/output delays, transition and load.
#[must_use]
pub fn sdc_single_clock(
    clk_port: &str,
    period_ns: f64,
    in_delay_ns: f64,
    out_delay_ns: f64,
    load_pf: f64,
) -> String {
    let mut s = String::new();
    let _ = writeln!(s, "# Generated by ruststa-fixtures; do not edit.");
    let _ = writeln!(
        s,
        "create_clock -name clk -period {period_ns:.4} [get_ports {clk_port}]"
    );
    let _ = writeln!(s, "set_clock_transition 0.1000 [get_clocks clk]");
    let _ = writeln!(s, "set_clock_uncertainty 0.0200 [get_clocks clk]");
    let _ = writeln!(s, "set_input_transition 0.1000 [all_inputs]");
    let _ = writeln!(
        s,
        "set_input_delay -clock clk {in_delay_ns:.4} [all_inputs]"
    );
    let _ = writeln!(
        s,
        "set_output_delay -clock clk {out_delay_ns:.4} [all_outputs]"
    );
    let _ = writeln!(s, "set_load {load_pf:.4} [all_outputs]");
    s
}

/// Generates a dual-clock SDC constraint deck with two clocks (`clk_a`, `clk_b`) and input/output
/// boundary constraints.
#[must_use]
pub fn sdc_dual_clock(
    clk_a: &str,
    period_a: f64,
    clk_b: &str,
    period_b: f64,
    in_delay_ns: f64,
    out_delay_ns: f64,
) -> String {
    let mut s = String::new();
    let _ = writeln!(s, "# Generated by ruststa-fixtures; do not edit.");
    let _ = writeln!(
        s,
        "create_clock -name clk_a -period {period_a:.4} [get_ports {clk_a}]"
    );
    let _ = writeln!(
        s,
        "create_clock -name clk_b -period {period_b:.4} [get_ports {clk_b}]"
    );
    let _ = writeln!(s, "set_clock_transition 0.1000 [all_clocks]");
    let _ = writeln!(s, "set_clock_uncertainty 0.0250 [all_clocks]");
    let _ = writeln!(s, "set_input_transition 0.1000 [all_inputs]");
    let _ = writeln!(
        s,
        "set_input_delay -clock clk_a {in_delay_ns:.4} [all_inputs]"
    );
    let _ = writeln!(
        s,
        "set_output_delay -clock clk_b {out_delay_ns:.4} [all_outputs]"
    );
    let _ = writeln!(s, "set_load 0.0200 [all_outputs]");
    s
}

/// Generates the canonical SDC constraint deck for a [`NetlistFixture`].
#[must_use]
pub fn sdc_for_fixture(fixture: &NetlistFixture) -> String {
    if fixture.clocks.len() >= 2 {
        sdc_dual_clock(&fixture.clocks[0], 2.0, &fixture.clocks[1], 3.0, 0.2, 0.2)
    } else {
        let clk = fixture.clocks.first().map_or("clk", String::as_str);
        sdc_single_clock(clk, 2.0, 0.2, 0.2, 0.02)
    }
}

/// Returns `(name, sdc_text)` pairs for all canonical synthetic netlists written to
/// `verification/fixtures/synthetic/sta/sdc/*.sdc`.
#[must_use]
pub fn synthetic_sdcs() -> Vec<(String, String)> {
    synthetic_netlists()
        .into_iter()
        .map(|f| {
            let sdc = sdc_for_fixture(&f);
            (f.name, sdc)
        })
        .collect()
}
